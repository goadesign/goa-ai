// These tests exercise shared child codecs through distinct public roots. Each
// root must retain its own required fields, null rules, and reported field path.
package jsoncodec

import (
	"fmt"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
	"goa.design/goa/v3/dsl"
	"goa.design/goa/v3/expr"
)

func TestSharedChainGeneratedProgram(t *testing.T) {
	const count = 32
	files, err := generate(t, func() {
		var child expr.UserType
		for index := count - 1; index >= 0; index-- {
			next := child
			child = located(fmt.Sprintf("Chain%02d", index), func() {
				dsl.Attribute("label", dsl.String, func() { dsl.MinLength(1) })
				if next != nil {
					dsl.Attribute("next", next)
				}
				dsl.Required("label")
			})
		}
	})
	require.NoError(t, err)
	source := generatedSource(t, files, "gen/types")
	t.Logf("chain roots=%d generated bytes=%d", count, len(source))
	for index := range count {
		name := fmt.Sprintf("Chain%02d", index)
		require.Contains(t, source, "func Encode"+name+"(")
		require.Contains(t, source, "func Decode"+name+"(")
	}
	runGo(t, compileModule(t, files), "test", "./gen/...")
}

func TestSharedHelpersPreserveRootContracts(t *testing.T) {
	files, err := generate(t, func() {
		child := located("Child", func() {
			dsl.Attribute("label", dsl.String, func() { dsl.MinLength(1) })
			dsl.Attribute("next", "Child")
			dsl.Required("label")
		})
		located("RequiredRoot", func() {
			dsl.Attribute("primary", child)
			dsl.Attribute("children", dsl.ArrayOfRequired(child))
			dsl.Required("primary")
		})
		located("OptionalRoot", func() {
			dsl.Attribute("secondary", child)
			dsl.Attribute("children", dsl.ArrayOf(child))
		})
	})
	require.NoError(t, err)
	root := compileModule(t, files)
	require.NoError(t, os.WriteFile(filepath.Join(root, "gen/types/shared_helpers_test.go"), []byte(sharedHelpersBehavior), 0o600)) // #nosec G703 -- compileModule creates this test directory and the child name is fixed.
	runGo(t, root, "test", "-count=1", "./gen/...")
}

const sharedHelpersBehavior = `package types_test

import (
 "strings"
 "testing"

 gentypes "codec.local/gen/types"
)

func TestRootRules(t *testing.T) {
 optional, err := gentypes.DecodeOptionalRoot([]byte("{}"))
 if err != nil || optional.Secondary != nil { t.Fatalf("optional child: %#v %v", optional, err) }
 if _, err := gentypes.EncodeOptionalRoot(optional); err != nil { t.Fatal(err) }
 if _, err := gentypes.DecodeRequiredRoot([]byte("{}")); err == nil { t.Fatal("accepted missing required child") }
 if _, err := gentypes.EncodeRequiredRoot(&gentypes.RequiredRoot{}); err == nil { t.Fatal("encoded missing required child") }

 nullable, err := gentypes.DecodeOptionalRoot([]byte("{\"children\":[null,{\"label\":\"ok\"}]}"))
 if err != nil || len(nullable.Children) != 2 || nullable.Children[0] != nil { t.Fatalf("nullable children: %#v %v", nullable, err) }
 if _, err := gentypes.EncodeOptionalRoot(nullable); err != nil { t.Fatal(err) }
 if _, err := gentypes.DecodeRequiredRoot([]byte("{\"primary\":{\"label\":\"ok\"},\"children\":[null]}")); err == nil { t.Fatal("accepted null strict child") }
 if _, err := gentypes.EncodeRequiredRoot(&gentypes.RequiredRoot{Primary: &gentypes.Child{Label: "ok"}, Children: []*gentypes.Child{nil}}); err == nil { t.Fatal("encoded null strict child") }
 for _, document := range []string{
  "{\"primary\":{\"label\":\"\"}}",
  "{\"primary\":{\"label\":\"ok\",\"unknown\":true}}",
  "{\"primary\":{\"label\":\"ok\",\"label\":\"again\"}}",
 } {
  if _, err := gentypes.DecodeRequiredRoot([]byte(document)); err == nil { t.Fatalf("accepted %s", document) }
 }
}

func TestSharedChildErrorPathsAndCycles(t *testing.T) {
 child := &gentypes.Child{Label: string([]byte{0xff})}
 for _, root := range []struct { path string; encode func() ([]byte, error) }{
  {"$[\"primary\"][\"label\"]", func() ([]byte,error) { return gentypes.EncodeRequiredRoot(&gentypes.RequiredRoot{Primary: child}) }},
  {"$[\"secondary\"][\"label\"]", func() ([]byte,error) { return gentypes.EncodeOptionalRoot(&gentypes.OptionalRoot{Secondary: child}) }},
 } {
  if _, err := root.encode(); err == nil || !strings.Contains(err.Error(), root.path) { t.Fatalf("lost path %s: %v", root.path, err) }
 }
 child.Label = "ok"
 child.Next = child
 if _, err := gentypes.EncodeChild(child); err == nil || !strings.Contains(err.Error(), "cyclic Go value") { t.Fatalf("root cycle: %v", err) }
 if _, err := gentypes.EncodeRequiredRoot(&gentypes.RequiredRoot{Primary: child}); err == nil || !strings.Contains(err.Error(), "$[\"primary\"][\"next\"]") { t.Fatalf("nested cycle: %v", err) }
 child.Next = nil
 reused := &gentypes.OptionalRoot{Secondary: child, Children: []*gentypes.Child{child, child}}
 encoded, err := gentypes.EncodeOptionalRoot(reused)
 if err != nil { t.Fatalf("acyclic repeated child rejected: %v", err) }
 if _, err := gentypes.DecodeOptionalRoot(encoded); err != nil { t.Fatal(err) }
}
`
